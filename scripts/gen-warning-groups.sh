#!/bin/sh
# Regenerates crates/merlin/src/warning_groups.txt from clang's warning
# groups (`diagtool tree`, LLVM's): for each -W flag merlin gives a warning
# of (a string literal of crates/merlin/src that names one) and each the cc
# driver does, the groups that hold it, itself included, so that -Wno-X,
# -Werror=X and the like act on X's warnings as clang's do. merlin reads
# the file (merlin::warnings), and `cargo xtask kernel` writes cc1's and
# cc's tables from it (crates/xtask/src/c_tables.rs). LLVM is needed only
# here; the file is committed.
#
#   scripts/gen-warning-groups.sh            # diagtool on PATH
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
tree=$(mktemp)
trap 'rm -f "$tree"' EXIT
diagtool tree > "$tree"
# The flags: merlin's string literals (`#warnings` among them), and the
# driver's own (kernel/user/cc.c): its unused arguments and its -O
# warnings.
{
    grep -rhoE '"#?[a-z0-9][a-z0-9+-]*"' "$root"/crates/merlin/src/*.rs | tr -d '"'
    printf '%s\n' unused-command-line-argument deprecated deprecated-ofast
} | sort -u > "$tree.flags"
{
    echo "// FLAG: GROUP...: the clang warning groups that hold each -W flag merlin and the cc driver"
    echo "// give a warning of (FLAG itself holds it too), generated by"
    echo "// scripts/gen-warning-groups.sh from clang's \`diagtool tree\`. Do not edit."
    awk -v flagfile="$tree.flags" '
        BEGIN { while ((getline f < flagfile) > 0) want[f] = 1 }
        /^ *-W/ {
            match($0, /^ */)
            depth = RLENGTH / 2
            name = substr($0, RLENGTH + 3)
            stack[depth] = name
            if (!(name in seen)) { seen[name] = 1; order[++n] = name }
            for (k = 0; k < depth; k++) {
                if (stack[k] != "" && !((name, stack[k]) in has)) {
                    has[name, stack[k]] = 1
                    groups[name] = groups[name] " " stack[k]
                }
            }
        }
        END {
            for (i = 1; i <= n; i++) {
                name = order[i]
                if (name in want) print name ":" groups[name]
            }
        }' "$tree" | sort
} > "$root/crates/merlin/src/warning_groups.txt"
rm -f "$tree.flags"
