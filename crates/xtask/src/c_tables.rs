//! The tables of the tools that run on Camelot, written from the host's, so
//! that the C programs and the Rust ones they are ported from can't disagree
//! about them. What is code rather than data is ported by hand, and the
//! self-hosting tests (`tests/selfhost.rs`) check it.
//!
//! - The assembler (`kernel/user/as`): the mnemonics' encodings and the
//!   funct3 values the pseudo-instructions use (merlin-as's `encode`, RV64's
//!   own tables included), the relocation types (`reloc`), the ISA string
//!   of `.riscv.attributes` (`elf`), the section
//!   types and flags, `.section`'s flag letters and type names and the
//!   sections LLVM predefines (`section`), and the major opcodes, register
//!   and CSR names, with the CSRs only RV32 has (`excalibur`).
//!   [`AS_TABLES_H`] declares the tables and defines the constants;
//!   [`AS_TABLES_C`] defines the tables, once for the whole program.
//! - The linker (`kernel/user/ld`): the ELF constants (section types and
//!   flags, symbol bindings and types, special section indices, program
//!   header types and flags) and the
//!   relocation types' numbers and names (`elf::reloc_name`, which
//!   merlin-ld's messages use), all the elf crate's, in [`LD_TABLES_H`] and
//!   [`LD_TABLES_C`].
//!
//! `cargo xtask kernel` writes them all (before it builds the user
//! programs), and a test checks the committed files are what [`files`]
//! gives.

use merlin_as::encode;
use merlin_as::reloc::RelocKind;
use merlin_as::section;
use std::fmt::Write;
use std::path::Path;

/// The assembler's header, relative to the repository root.
pub const AS_TABLES_H: &str = "kernel/user/as/tables.h";
/// The assembler's tables.
pub const AS_TABLES_C: &str = "kernel/user/as/tables.c";
/// The linker's header.
pub const LD_TABLES_H: &str = "kernel/user/ld/tables.h";
/// The linker's tables.
pub const LD_TABLES_C: &str = "kernel/user/ld/tables.c";

const NOTICE: &str =
    "/* Generated by `cargo xtask kernel` from merlin-as's tables (crates/merlin-as/src/encode.rs,\n \
                      * reloc.rs, elf.rs, section.rs) and excalibur's (opcodes, registers, CSRs): do not\n \
                      * edit. See crates/xtask/src/c_tables.rs. */\n";

const LD_NOTICE: &str =
    "/* Generated by `cargo xtask kernel` from the elf crate's ELF constants and relocation names\n \
                         * (crates/elf/src/lib.rs): do not edit. See crates/xtask/src/c_tables.rs. */\n";

/// Every generated file: (path from the repository root, text).
pub fn files() -> Vec<(&'static str, String)> {
    vec![
        (AS_TABLES_H, generate_h()),
        (AS_TABLES_C, generate_c()),
        (LD_TABLES_H, generate_ld_h()),
        (LD_TABLES_C, generate_ld_c()),
    ]
}

/// The relocation types the elf crate names, by number.
fn reloc_names() -> Vec<(u32, &'static str)> {
    (0..256)
        .filter_map(|t| elf::reloc_name(t).map(|n| (t, n)))
        .collect()
}

