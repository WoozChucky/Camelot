/// The text of [`LD_TABLES_H`].
pub fn generate_ld_h() -> String {
    let mut s = String::from(LD_NOTICE);
    s.push_str("#ifndef LD_TABLES_H\n#define LD_TABLES_H\n\n/* ELF constants (the elf crate's). */\n");
    for (n, v) in elf_constants() {
        let _ = writeln!(s, "#define {n} {v:#x}");
    }
    s.push_str("\n/* Relocation types (psABI numbers). */\n");
    for (t, n) in reloc_names() {
        let _ = writeln!(s, "#define {n} {t}");
    }
    s.push_str(
        "\n/* A relocation type's name, for messages. The table ends with a NULL name. */\n\
         struct reloc_name {\n    unsigned int type;\n    const char *name;\n};\n\
         extern const struct reloc_name RELOC_NAMES[];\n\n#endif\n",
    );
    s
}

/// The text of [`LD_TABLES_C`].
pub fn generate_ld_c() -> String {
    let mut s = String::from(LD_NOTICE);
    s.push_str("#include \"tables.h\"\n\nconst struct reloc_name RELOC_NAMES[] = {\n");
    for (t, n) in reloc_names() {
        let _ = writeln!(s, "    {{{t}, \"{n}\"}},");
    }
    s.push_str("    {0, 0},\n};\n");
    s
}

/// Rows of a name and two values (`struct as_op3`).
type Op3Rows = &'static [(&'static str, u32, u32)];

/// The tables of a name and two values, by C name: the base set's, then
/// RV64's own (OP-32's).
fn tables3() -> [(&'static str, Op3Rows); 4] {
    [
        ("OP_FUNCT", encode::OP_FUNCT),
        ("SHIFT_FUNCT", encode::SHIFT_FUNCT),
        ("OP_32_FUNCT", encode::OP_32_FUNCT),
        ("SHIFT_32_FUNCT", encode::SHIFT_32_FUNCT),
    ]
}

/// The CSR tables, written apart from the encodings: every name excalibur
/// knows, and the ones only RV32 has (`excalibur::csr::rv32_only`: the high
/// halves of 64-bit CSRs and the odd `pmpcfg`s), which are no name here, and
/// which merlin-as reports as RV32's, as LLVM does.
const CSR_TABLES: [&str; 2] = ["CSR_NAMES", "CSR_RV32_ONLY"];

/// The tables of a name and one value (`struct as_op2`), by C name.
fn tables2() -> Vec<(&'static str, Vec<(&'static str, u32)>)> {
    let csrs: Vec<(&str, u32)> = (0..4096u16)
        .filter_map(|a| excalibur::csr::name(a, excalibur::Xlen::Rv32).map(|n| (n, u32::from(a))))
        .collect();
    let rv32_only: Vec<(&str, u32)> = csrs
        .iter()
        .copied()
        .filter(|&(_, a)| excalibur::csr::rv32_only(a as u16))
        .collect();
    vec![
        ("OP_IMM_FUNCT3", encode::OP_IMM_FUNCT3.to_vec()),
        ("LOAD_FUNCT3", encode::LOAD_FUNCT3.to_vec()),
        ("STORE_FUNCT3", encode::STORE_FUNCT3.to_vec()),
        ("BRANCH_FUNCT3", encode::BRANCH_FUNCT3.to_vec()),
        ("CSR_FUNCT3", encode::CSR_FUNCT3.to_vec()),
        ("ATOMIC_FUNCT5", encode::ATOMIC_FUNCT5.to_vec()),
        ("SYSTEM_FUNCT12", encode::SYSTEM_FUNCT12.to_vec()),
        ("OP_IMM_32_FUNCT3", encode::OP_IMM_32_FUNCT3.to_vec()),
        ("LOAD_RV64_FUNCT3", encode::LOAD_RV64_FUNCT3.to_vec()),
        ("STORE_RV64_FUNCT3", encode::STORE_RV64_FUNCT3.to_vec()),
        ("CSR_NAMES", csrs),
        ("CSR_RV32_ONLY", rv32_only),
    ]
}

/// The section types and flags of merlin-as's `section` module: (C name,
/// value). Every flag fits in 32 bits, ELF32's `sh_flags`, and the C
/// assembler keeps them in an `unsigned int`.
fn section_constants() -> Vec<(&'static str, u32)> {
    use section::*;
    let flag = |f: u64| u32::try_from(f).expect("a 32-bit section flag");
    vec![
        ("SHT_PROGBITS", SHT_PROGBITS),
        ("SHT_NOTE", SHT_NOTE),
        ("SHT_NOBITS", SHT_NOBITS),
        ("SHT_INIT_ARRAY", SHT_INIT_ARRAY),
        ("SHT_FINI_ARRAY", SHT_FINI_ARRAY),
        ("SHT_PREINIT_ARRAY", SHT_PREINIT_ARRAY),
        ("SHT_RISCV_ATTRIBUTES", SHT_RISCV_ATTRIBUTES),
        ("SHF_WRITE", flag(SHF_WRITE)),
        ("SHF_ALLOC", flag(SHF_ALLOC)),
        ("SHF_EXECINSTR", flag(SHF_EXECINSTR)),
        ("SHF_MERGE", flag(SHF_MERGE)),
        ("SHF_STRINGS", flag(SHF_STRINGS)),
        ("SHF_TLS", flag(SHF_TLS)),
    ]
}

/// The text of [`AS_TABLES_H`].
pub fn generate_h() -> String {
    let mut s = String::from(NOTICE);
    s.push_str(
        "#ifndef AS_TABLES_H\n#define AS_TABLES_H\n\n\
         /* A mnemonic and two fields (funct3, funct7). Tables end with a NULL name. */\n\
         struct as_op3 {\n    const char *name;\n    unsigned int a;\n    unsigned int b;\n};\n\n\
         /* A mnemonic, or a name, and one value. */\n\
         struct as_op2 {\n    const char *name;\n    unsigned int value;\n};\n\n",
    );

    s.push_str("/* Major opcodes, bits [6:0] (spec section 4). */\n");
    for (name, v) in [
        ("LUI", excalibur::opcode::OP_LUI),
        ("AUIPC", excalibur::opcode::OP_AUIPC),
        ("JAL", excalibur::opcode::OP_JAL),
        ("JALR", excalibur::opcode::OP_JALR),
        ("BRANCH", excalibur::opcode::OP_BRANCH),
        ("LOAD", excalibur::opcode::OP_LOAD),
        ("STORE", excalibur::opcode::OP_STORE),
        ("OP_IMM", excalibur::opcode::OP_IMM),
        ("OP_IMM_32", excalibur::opcode::OP_IMM_32),
        ("OP", excalibur::opcode::OP_OP),
        ("OP_32", excalibur::opcode::OP_32),
        ("MISC_MEM", excalibur::opcode::OP_MISC_MEM),
        ("SYSTEM", excalibur::opcode::OP_SYSTEM),
        ("AMO", excalibur::opcode::OP_AMO),
        ("CUSTOM_0", excalibur::opcode::OP_CUSTOM0),
    ] {
        let _ = writeln!(s, "#define OPC_{name} {v:#04x}");
    }

    s.push_str(
        "\n/* funct3 values the pseudo-instructions use by name (CSR_IMM: the immediate CSR forms). */\n",
    );
    for (name, v) in encode::NAMED_FUNCT3 {
        let _ = writeln!(s, "#define F_{name} {v}");
    }

    s.push_str(
        "\n/* The encodings of the real instructions, by format (merlin-as's encode.rs); the\n \
         * _32_ and _RV64_ ones are RV64's own, beyond the base set. */\n",
    );
    for (name, _) in tables3() {
        let _ = writeln!(s, "extern const struct as_op3 {name}[];");
    }
    for (name, _) in tables2().iter().filter(|(n, _)| !CSR_TABLES.contains(n)) {
        let _ = writeln!(s, "extern const struct as_op2 {name}[];");
    }

    s.push_str("\n/* Register ABI names, by number (and x0-x31, and fp for s0). */\n");
    s.push_str("extern const char *const REG_NAMES[32];\n");

    s.push_str(
        "\n/* CSR names and numbers (excalibur's csr.rs): every one excalibur knows, and those\n \
         * of them only RV32 has, which are no name here (an error says they are RV32's, as\n \
         * LLVM's does); and the counters' numbers. */\n",
    );
    s.push_str("extern const struct as_op2 CSR_NAMES[];\nextern const struct as_op2 CSR_RV32_ONLY[];\n");
    for (name, v) in [
        ("CYCLE", excalibur::csr::CYCLE),
        ("TIME", excalibur::csr::TIME),
        ("INSTRET", excalibur::csr::INSTRET),
        ("CYCLEH", excalibur::csr::CYCLEH),
        ("TIMEH", excalibur::csr::TIMEH),
        ("INSTRETH", excalibur::csr::INSTRETH),
    ] {
        let _ = writeln!(s, "#define CSR_{name} {v:#05x}");
    }

    s.push_str("\n/* Section types and flags (merlin-as's section.rs). */\n");
    for (name, v) in section_constants() {
        let _ = writeln!(s, "#define {name} {v:#x}");
    }
    s.push_str(
        "\n/* `.section`'s flag letters, each a one-letter name, and its type names. */\n\
         extern const struct as_op2 SECTION_FLAGS[];\n\
         extern const struct as_op2 SECTION_TYPES[];\n\
         \n/* The sections LLVM has before the first line, with their type, flags and\n \
         * entry size. The table ends with a NULL name. */\n\
         struct as_section {\n    const char *name;\n    unsigned int ty;\n    unsigned int flags;\n    \
         unsigned int entsize;\n};\n\
         extern const struct as_section PREDEFINED_SECTIONS[];\n",
    );

    s.push_str("\n/* Relocation types (psABI numbers): what the assembler calls a fixup's kind too. */\n");
    for k in RelocKind::ALL {
        let _ = writeln!(s, "#define {} {}", k.name(), k.elf_type());
    }

    let _ = writeln!(
        s,
        "\n/* Tag_RISCV_arch in every object's .riscv.attributes (merlin-as's elf.rs). */\n\
         #define RISCV_ARCH \"{}\"\n\n#endif",
        merlin_as::elf::ARCH
    );
    s
}

/// The text of [`AS_TABLES_C`].
pub fn generate_c() -> String {
    let mut s = String::from(NOTICE);
    s.push_str("#include \"tables.h\"\n");
    for (name, rows) in tables3() {
        let _ = writeln!(s, "\nconst struct as_op3 {name}[] = {{");
        for (m, a, b) in rows {
            let _ = writeln!(s, "    {{\"{m}\", {a:#x}, {b:#x}}},");
        }
        s.push_str("    {0, 0, 0},\n};\n");
    }
    for (name, rows) in tables2() {
        let _ = writeln!(s, "\nconst struct as_op2 {name}[] = {{");
        for (m, v) in rows {
            let _ = writeln!(s, "    {{\"{m}\", {v:#x}}},");
        }
        s.push_str("    {0, 0},\n};\n");
    }
    // `.section`'s tables. The flags fit in 32 bits (section_constants).
    s.push_str("\nconst struct as_op2 SECTION_FLAGS[] = {\n");
    for (letter, f) in section::FLAG_LETTERS {
        let _ = writeln!(
            s,
            "    {{\"{}\", {:#x}}},",
            letter as char,
            u32::try_from(f).unwrap()
        );
    }
    s.push_str("    {0, 0},\n};\n\nconst struct as_op2 SECTION_TYPES[] = {\n");
    for (name, t) in section::TYPE_NAMES {
        let _ = writeln!(s, "    {{\"{name}\", {t:#x}}},");
    }
    s.push_str("    {0, 0},\n};\n\nconst struct as_section PREDEFINED_SECTIONS[] = {\n");
    for &(name, ty, flags, entsize) in section::PREDEFINED {
        let (flags, entsize) = (u32::try_from(flags).unwrap(), u32::try_from(entsize).unwrap());
        let _ = writeln!(s, "    {{\"{name}\", {ty:#x}, {flags:#x}, {entsize}}},");
    }
    s.push_str("    {0, 0, 0, 0},\n};\n");

    s.push_str("\nconst char *const REG_NAMES[32] = {\n");
    for chunk in excalibur::reg::ABI_NAMES.chunks(8) {
        let names: Vec<String> = chunk.iter().map(|n| format!("\"{n}\"")).collect();
        let _ = writeln!(s, "    {},", names.join(", "));
    }
    s.push_str("};\n");
    s
}

/// Writes every file of [`files`] under `root` that is not what it should
/// be. Returns the files it wrote.
pub fn write(root: &Path) -> Result<Vec<&'static str>, String> {
    let mut wrote = Vec::new();
    for (file, text) in files() {
        let path = root.join(file);
        if std::fs::read_to_string(&path).is_ok_and(|old| old.replace('\r', "") == text) {
            continue;
        }
        std::fs::write(&path, text).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
        wrote.push(file);
    }
    Ok(wrote)
}
