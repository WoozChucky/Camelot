//! The tables of the assembler that runs on Camelot (`kernel/user/as`), written
//! from the host's: the mnemonics' encodings (merlin-as's `encode` tables),
//! the major opcodes, register and CSR names (`excalibur`), the relocation
//! types and the ISA string of `.riscv.attributes`. The C program includes the
//! generated header, so the two assemblers can't disagree about them.
//!
//! `cargo xtask kernel` writes [`TABLES_H`] (before it builds the user
//! programs), and a test checks the committed file is what [`generate`]
//! gives.

use merlin_as::encode;
use merlin_as::reloc::RelocKind;
use std::fmt::Write;
use std::path::Path;

/// Where the header goes, relative to the repository root.
pub const TABLES_H: &str = "kernel/user/as/tables.h";

/// A `{ "name", a, b }` table, ending with a `{ 0 }` entry.
fn table3(out: &mut String, name: &str, rows: &[(&str, u32, u32)]) {
    let _ = writeln!(out, "static const struct as_op3 {name}[] = {{");
    for (m, a, b) in rows {
        let _ = writeln!(out, "    {{\"{m}\", {a:#x}, {b:#x}}},");
    }
    let _ = writeln!(out, "    {{0, 0, 0}},\n}};\n");
}

/// A `{ "name", value }` table, ending with a `{ 0 }` entry.
fn table2(out: &mut String, name: &str, rows: &[(&str, u32)]) {
    let _ = writeln!(out, "static const struct as_op2 {name}[] = {{");
    for (m, v) in rows {
        let _ = writeln!(out, "    {{\"{m}\", {v:#x}}},");
    }
    let _ = writeln!(out, "    {{0, 0}},\n}};\n");
}

/// The text of [`TABLES_H`].
pub fn generate() -> String {
    let mut s = String::new();
    s.push_str(
        "/* Generated by `cargo xtask kernel` from merlin-as's tables (crates/merlin-as/src/encode.rs,\n \
         * reloc.rs, elf.rs) and excalibur's (opcodes, registers, CSRs): do not edit. See\n \
         * crates/xtask/src/as_tables.rs. Included by the assembler's C files that need it. */\n\
         #ifndef AS_TABLES_H\n#define AS_TABLES_H\n\n\
         /* A mnemonic and two fields (funct3, funct7). */\n\
         struct as_op3 {\n    const char *name;\n    unsigned int a;\n    unsigned int b;\n};\n\n\
         /* A mnemonic, or a name, and one value. */\n\
         struct as_op2 {\n    const char *name;\n    unsigned int value;\n};\n\n",
    );

    s.push_str("/* Major opcodes, bits [6:0] (spec section 4). */\n");
    for (name, v) in [
        ("LUI", excalibur::opcode::OP_LUI),
        ("AUIPC", excalibur::opcode::OP_AUIPC),
        ("JAL", excalibur::opcode::OP_JAL),
        ("JALR", excalibur::opcode::OP_JALR),
        ("BRANCH", excalibur::opcode::OP_BRANCH),
        ("LOAD", excalibur::opcode::OP_LOAD),
        ("STORE", excalibur::opcode::OP_STORE),
        ("OP_IMM", excalibur::opcode::OP_IMM),
        ("OP", excalibur::opcode::OP_OP),
        ("MISC_MEM", excalibur::opcode::OP_MISC_MEM),
        ("SYSTEM", excalibur::opcode::OP_SYSTEM),
        ("AMO", excalibur::opcode::OP_AMO),
        ("CUSTOM_0", excalibur::opcode::OP_CUSTOM0),
    ] {
        let _ = writeln!(s, "#define OPC_{name} {v:#04x}");
    }
    s.push('\n');

    s.push_str("/* The encodings of the real instructions, by format (merlin-as's encode.rs). */\n");
    table3(&mut s, "OP_FUNCT", encode::OP_FUNCT);
    table2(&mut s, "OP_IMM_FUNCT3", encode::OP_IMM_FUNCT3);
    table3(&mut s, "SHIFT_FUNCT", encode::SHIFT_FUNCT);
    table2(&mut s, "LOAD_FUNCT3", encode::LOAD_FUNCT3);
    table2(&mut s, "STORE_FUNCT3", encode::STORE_FUNCT3);
    table2(&mut s, "BRANCH_FUNCT3", encode::BRANCH_FUNCT3);
    table2(&mut s, "CSR_FUNCT3", encode::CSR_FUNCT3);
    table2(&mut s, "ATOMIC_FUNCT5", encode::ATOMIC_FUNCT5);
    table2(&mut s, "SYSTEM_FUNCT12", encode::SYSTEM_FUNCT12);

    s.push_str("/* Register ABI names, by number (and x0-x31, and fp for s0). */\n");
    s.push_str("static const char *const REG_NAMES[32] = {\n");
    for chunk in excalibur::reg::ABI_NAMES.chunks(8) {
        let names: Vec<String> = chunk.iter().map(|n| format!("\"{n}\"")).collect();
        let _ = writeln!(s, "    {},", names.join(", "));
    }
    s.push_str("};\n\n");

    let csrs: Vec<(&str, u32)> = (0..4096u16)
        .filter_map(|a| excalibur::csr::name(a).map(|n| (n, u32::from(a))))
        .collect();
    s.push_str("/* CSR names and numbers (excalibur's csr.rs). */\n");
    table2(&mut s, "CSR_NAMES", &csrs);
    for (name, v) in [
        ("CYCLE", excalibur::csr::CYCLE),
        ("TIME", excalibur::csr::TIME),
        ("INSTRET", excalibur::csr::INSTRET),
        ("CYCLEH", excalibur::csr::CYCLEH),
        ("TIMEH", excalibur::csr::TIMEH),
        ("INSTRETH", excalibur::csr::INSTRETH),
    ] {
        let _ = writeln!(s, "#define CSR_{name} {v:#05x}");
    }
    s.push('\n');

    s.push_str("/* Relocation types (psABI numbers) and their names. */\n");
    for k in RelocKind::ALL {
        let _ = writeln!(s, "#define {} {}", k.name(), k.elf_type());
    }
    s.push('\n');

    let _ = writeln!(
        s,
        "/* Tag_RISCV_arch in every object's .riscv.attributes (merlin-as's elf.rs). */\n\
         #define RISCV_ARCH \"{}\"\n\n#endif",
        merlin_as::elf::ARCH
    );
    s
}

/// Writes [`TABLES_H`] under `root` if it is not what [`generate`] gives.
/// Returns whether it wrote it.
pub fn write(root: &Path) -> Result<bool, String> {
    let path = root.join(TABLES_H);
    let text = generate();
    if std::fs::read_to_string(&path).is_ok_and(|old| old.replace('\r', "") == text) {
        return Ok(false);
    }
    std::fs::write(&path, text).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    Ok(true)
}
