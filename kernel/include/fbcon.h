/* The framebuffer console (spec section 10, "Framebuffer console"): what the
 * kernel prints and the console device's output, on the display as well as
 * the UART, as Linux's fbcon draws a VT on fbdev. 80 columns by 30 rows of
 * Spleen's 8x16 glyphs (font.c) at 640x480, in VRAM, with the control
 * characters a terminal acts on (CR, LF as CR LF, BS, TAB) and a small part
 * of ANSI's escape sequences: SGR's colours, bold and reverse, the cursor's
 * moves and position (CUU, CUD, CUF, CUB, CUP) and erasing (ED, EL).
 *
 * Text goes into a grid of cells first. A cell is drawn into VRAM as it
 * changes, unless the grid has scrolled since the last flush: a scroll
 * moves the pixels up, which waits for fbcon_flush(), called on hart 0's
 * clock tick (TICK_HZ times a second), so that a burst of lines scrolls
 * once. The flush also draws the cursor, an inverse cell, and tells the
 * display a frame is ready (fb_present_frame).
 *
 * While a program has /dev/fb0 open or mapped the display is the program's:
 * the console keeps its grid up to date but doesn't draw (fbcon_suspend);
 * when the program lets go, the next flush draws the whole grid again
 * (fbcon_resume), as Linux's VT comes back after a graphical program.
 *
 * Locking: the console's state is under uart_tx_lock (uart.h), which every
 * writer to the UART holds already; fbcon_putc() and fbcon_puts() are called
 * with it held, or without locks once the kernel panics, as kprintf()
 * writes then. */
#ifndef CAMELOT_FBCON_H
#define CAMELOT_FBCON_H

#include "types.h"

/* The grid. */
#define FBCON_COLS 80
#define FBCON_ROWS 30

/* Spleen 8x16 as PSF2 (font.c, generated by `cargo xtask kernel` from
 * fonts/spleen-8x16.psfu). */
extern const usize font_psf2_size;
extern const u8 font_psf2[];

/* Starts drawing on the display, with the text printed since boot: from
 * fb_init(), once VRAM shows 640x480. Nothing if the font isn't 8x16 or
 * the mode smaller than the grid. */
void fbcon_init(void);

/* Writes `c` / `s` to the grid, and the cells it changes to VRAM if no
 * scroll waits for the flush. Holding uart_tx_lock (or panicking). */
void fbcon_putc(char c);
void fbcon_puts(const char *s);

/* Scrolls VRAM to match the grid, draws the cells that changed and the
 * cursor and presents the frame, if anything changed: hart 0's clock tick
 * (trap.c). Takes uart_tx_lock. */
void fbcon_flush(void);

/* The same once the kernel panics, without locks: the panic's report on the
 * display before the machine stops. */
void fbcon_panic_flush(void);

/* A program takes the display (fb_open, the first open file of /dev/fb0) /
 * gives it back, the display back at 640x480 in VRAM (release_display).
 * Holding fb_lock; they take uart_tx_lock. */
void fbcon_suspend(void);
void fbcon_resume(void);

#endif
